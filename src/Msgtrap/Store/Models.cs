namespace Msgtrap.Store;

/// <summary>The lifecycle states a captured message can be in.</summary>
public static class MessageStatus
{
    /// <summary>Accepted, waiting for the simulated delivery delay to elapse.</summary>
    public const string Queued = "queued";

    /// <summary>The simulated handset received the message.</summary>
    public const string Delivered = "delivered";

    /// <summary>A <c>scheduled_date</c> was supplied; Msgtrap stores it but never delivers it.</summary>
    public const string Scheduled = "scheduled";

    /// <summary>Reserved for future failure simulation; not produced today.</summary>
    public const string Failed = "failed";
}

/// <summary>A single destination number and the Arkesel message id Msgtrap minted for it.</summary>
public sealed class Recipient
{
    /// <summary>Normalized number (separators and leading <c>+</c> removed).</summary>
    public string Number { get; set; } = "";

    /// <summary>Arkesel-style UUID returned to the caller as <c>id</c>.</summary>
    public string Id { get; set; } = "";

    /// <summary>Delivery state; mirrors the parent message.</summary>
    public string Status { get; set; } = MessageStatus.Queued;

    /// <summary>Reason for a per-recipient failure, if any.</summary>
    public string? Error { get; set; }

    /// <summary>Deep copy, so callers never observe a message mid-update.</summary>
    public Recipient Clone() => new() { Number = Number, Id = Id, Status = Status, Error = Error };
}

/// <summary>One entry in a message's delivery timeline.</summary>
public sealed class DeliveryLogEntry
{
    /// <summary>When the event happened (UTC).</summary>
    public DateTimeOffset At { get; set; }

    /// <summary>Status at that point, e.g. <c>queued</c>.</summary>
    public string Status { get; set; } = "";

    /// <summary>Human readable explanation shown in the UI.</summary>
    public string Message { get; set; } = "";
}

/// <summary>
/// One captured <c>POST /api/v2/sms/send</c> request, including everything the
/// UI needs to explain what happened.
/// </summary>
public sealed class CapturedMessage
{
    /// <summary>Request id (UUID) generated by Msgtrap.</summary>
    public string Id { get; set; } = "";

    /// <summary>Sender ID exactly as supplied.</summary>
    public string Sender { get; set; } = "";

    /// <summary>Accepted recipients, each with its own Arkesel message id.</summary>
    public List<Recipient> Recipients { get; set; } = [];

    /// <summary>Numbers that failed validation, returned in the <c>invalid numbers</c> bucket.</summary>
    public List<string> Invalid { get; set; } = [];

    /// <summary>Message body as supplied.</summary>
    public string Body { get; set; } = "";

    /// <summary><c>GSM-7</c> or <c>UCS-2</c>, same rule carriers apply.</summary>
    public string Encoding { get; set; } = "";

    /// <summary>Billed segments (1 for a single SMS, more for concatenated parts).</summary>
    public int Segments { get; set; }

    /// <summary>Billed characters/septets for the body.</summary>
    public int Chars { get; set; }

    /// <summary>True when the caller set Arkesel's <c>sandbox</c> flag.</summary>
    public bool Sandbox { get; set; }

    /// <summary>Requested <c>scheduled_date</c>, if any.</summary>
    public string? ScheduledFor { get; set; }

    /// <summary>Requested delivery callback URL, if any.</summary>
    public string? CallbackUrl { get; set; }

    /// <summary>
    /// Id of the provider adapter that accepted this message
    /// (e.g. <c>arkesel</c>, <c>twilio</c>), so the UI can label it.
    /// </summary>
    public string Provider { get; set; } = "";

    /// <summary>OTP metadata when this message was produced by the OTP endpoint.</summary>
    public OtpInfo? Otp { get; set; }

    /// <summary>Current state; see <see cref="MessageStatus"/>.</summary>
    public string Status { get; set; } = MessageStatus.Queued;

    /// <summary>Set when capture or delivery failed.</summary>
    public string? Error { get; set; }

    /// <summary>When the request was accepted (UTC).</summary>
    public DateTimeOffset CreatedAt { get; set; }

    /// <summary>When the simulated delivery completed (UTC).</summary>
    public DateTimeOffset? DeliveredAt { get; set; }

    /// <summary>Delay that was in effect when this message was queued.</summary>
    public int DeliveryDelayMs { get; set; }

    /// <summary>Chronological delivery events for the UI timeline.</summary>
    public List<DeliveryLogEntry> DeliveryLog { get; set; } = [];

    /// <summary>Raw JSON body as received, shown under "Raw request body".</summary>
    public Dictionary<string, object?>? Request { get; set; }

    /// <summary>Deep copy, so the store never hands out live instances.</summary>
    public CapturedMessage Clone() => new()
    {
        Id = Id,
        Sender = Sender,
        Recipients = Recipients.Select(r => r.Clone()).ToList(),
        Invalid = [.. Invalid],
        Body = Body,
        Encoding = Encoding,
        Segments = Segments,
        Chars = Chars,
        Sandbox = Sandbox,
        ScheduledFor = ScheduledFor,
        CallbackUrl = CallbackUrl,
        Provider = Provider,
        Otp = Otp?.Clone(),
        Status = Status,
        Error = Error,
        CreatedAt = CreatedAt,
        DeliveredAt = DeliveredAt,
        DeliveryDelayMs = DeliveryDelayMs,
        DeliveryLog = DeliveryLog.Select(l => new DeliveryLogEntry
        {
            At = l.At,
            Status = l.Status,
            Message = l.Message,
        }).ToList(),
        Request = Request,
    };
}

/// <summary>Runtime simulation switches surfaced in the UI settings panel.</summary>
public sealed class SimulatorSettings
{
    /// <summary>
    /// When true, every provider checks the credentials the caller supplied
    /// against <see cref="Credentials"/> and rejects mismatches.
    /// </summary>
    public bool EnforceCredentials { get; set; }

    /// <summary><c>""</c>, <c>402</c>, <c>403</c> or <c>500</c>: makes Arkesel sends fail on purpose.</summary>
    public string ForceError { get; set; } = "";

    /// <summary>
    /// Expected credentials per provider id, e.g.
    /// <c>twilio → { account-sid: "AC…", auth-token: "…" }</c>.
    /// Deterministic fake values so the UI can show what to paste into your app.
    /// </summary>
    public Dictionary<string, Dictionary<string, string>> Credentials { get; set; } = [];

    /// <summary>
    /// Providers switched off from the UI. Empty by default so a newly added
    /// provider is served without any configuration.
    /// </summary>
    public List<string> DisabledProviders { get; set; } = [];

    /// <summary>Queued-to-delivered delay in milliseconds; shared by every provider.</summary>
    public int DeliverAfterMs { get; set; } = 1500;

    /// <summary>Fake SMS credits reported by balance endpoints.</summary>
    public int SmsBalance { get; set; } = 2003;

    /// <summary>Fake main wallet balance reported as text.</summary>
    public string MainBalance { get; set; } = "GHS 20.99";

    /// <summary>Copy, so callers cannot mutate live settings without the lock.</summary>
    public SimulatorSettings Clone() => new()
    {
        EnforceCredentials = EnforceCredentials,
        ForceError = ForceError,
        Credentials = Credentials.ToDictionary(
            provider => provider.Key,
            provider => new Dictionary<string, string>(provider.Value)),
        DisabledProviders = [.. DisabledProviders],
        DeliverAfterMs = DeliverAfterMs,
        SmsBalance = SmsBalance,
        MainBalance = MainBalance,
    };
}

/// <summary>
/// Details of an OTP created by <c>POST /api/otp/generate</c>, attached to the
/// message that carried the code so the UI can reveal and copy it.
/// </summary>
public sealed class OtpInfo
{
    /// <summary>The generated code. Shown in the UI so you never need a real phone.</summary>
    public string Code { get; set; } = "";

    /// <summary><c>numeric</c> or <c>alphanumeric</c>.</summary>
    public string Type { get; set; } = "";

    /// <summary><c>sms</c> or <c>voice</c>. Voice is simulated without audio.</summary>
    public string Medium { get; set; } = "";

    /// <summary>Lifetime requested by the caller, in minutes.</summary>
    public int ExpiryMinutes { get; set; }

    /// <summary>Moment the code stops being accepted (UTC).</summary>
    public DateTimeOffset ExpiresAt { get; set; }

    /// <summary>True once <c>/api/otp/verify</c> accepted this code.</summary>
    public bool Verified { get; set; }

    /// <summary>When verification succeeded (UTC).</summary>
    public DateTimeOffset? VerifiedAt { get; set; }

    /// <summary>Number of failed verification attempts so far.</summary>
    public int Attempts { get; set; }

    /// <summary>Copy, so callers never observe an OTP mid-update.</summary>
    public OtpInfo Clone() => new()
    {
        Code = Code,
        Type = Type,
        Medium = Medium,
        ExpiryMinutes = ExpiryMinutes,
        ExpiresAt = ExpiresAt,
        Verified = Verified,
        VerifiedAt = VerifiedAt,
        Attempts = Attempts,
    };
}

/// <summary>Filter applied when listing the inbox.</summary>
/// <param name="Query">Free text matched against sender, body, numbers and ids.</param>
/// <param name="Status">Exact status match (e.g. <c>delivered</c>).</param>
/// <param name="Sender">Exact sender match.</param>
/// <param name="Recipient">Exact recipient number match.</param>
public sealed record MessageFilter(string? Query, string? Status, string? Sender, string? Recipient);

/// <summary>A change pushed to SSE subscribers.</summary>
/// <param name="Type">One of <c>message</c>, <c>update</c>, <c>delete</c>, <c>clear</c>, <c>settings</c>.</param>
/// <param name="Message">The affected message, for message/update events.</param>
/// <param name="Id">The affected id, for delete events.</param>
public sealed record StoreEvent(string Type, CapturedMessage? Message = null, string? Id = null);
